// Builds one page per card and a "credits that expire December 31" page from the app's library file.
// Usage: node scripts/build-pages.mjs [path/to/library.json]
// Default library: ../perkaboo/src/data/library.json (the app repo, next to this one). Re-run whenever the library changes.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const libraryPath = resolve(process.argv[2] ?? resolve(root, "../perkaboo/src/data/library.json"));
const lib = JSON.parse(readFileSync(libraryPath, "utf8"));

// Change this if the site moves to its own domain.
const SITE_URL = "https://sjbapps624-git.github.io/perkaboo-site";

// Only cards whose credits were verified with confidence A or B in the app repo's docs/library-verification.md.
// Add a card here only after checking it. (Delta SkyMiles Reserve is confidence C: not published.)
const PUBLISH = new Set([
  "amex-platinum", "amex-gold", "amex-business-platinum", "chase-sapphire-reserve", "chase-sapphire-preferred",
  "capital-one-venture-x", "hilton-honors-aspire", "marriott-bonvoy-brilliant", "citi-strata-premier",
]);

// Caveats worth stating next to a credit, keyed by "cardId:slug".
const NOTES = {
  "amex-platinum:uber": "Amex also lists extra Uber Cash in December. PerkaBoo tracks the $15 monthly amount.",
};

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const money = (c) => `$${(c / 100).toLocaleString("en-US", { minimumFractionDigits: c % 100 ? 2 : 0, maximumFractionDigits: 2 })}`;
const monthName = (iso) => new Date(`${iso}T00:00:00Z`).toLocaleDateString("en-US", { month: "long", day: "numeric", year: "numeric", timeZone: "UTC" });
const PER_YEAR = { monthly: 12, quarterly: 4, semiannual: 2, annual: 1 };

function resets(b) {
  if (b.cadence === "multiyear") return "Once every four years";
  if (b.resetBasis === "anniversary") return b.cadence === "annual" ? "Every year, on your card anniversary" : `${cap(b.cadence)}, counted from your card anniversary`;
  return {
    monthly: "Every month (last day of the month)",
    quarterly: "Every quarter: Mar 31, Jun 30, Sep 30, Dec 31",
    semiannual: "Twice a year: Jun 30 and Dec 31",
    annual: "Every calendar year (Dec 31)",
  }[b.cadence];
}
const cap = (s) => s[0].toUpperCase() + s.slice(1);

function annualValue(b) {
  if (b.cadence === "multiyear" || b.amountCents === 0) return 0;
  return b.amountCents * PER_YEAR[b.cadence];
}

const layout = ({ title, description, path, depth, body }) => {
  const up = "../".repeat(depth);
  return `<!doctype html>
<!-- Generated by scripts/build-pages.mjs from the PerkaBoo library (version ${lib.version}, updated ${lib.lastUpdated}). Do not edit by hand. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<meta name="description" content="${esc(description)}">
<link rel="canonical" href="${SITE_URL}/${path}">
<link rel="icon" href="${up}assets/favicon.png">
<link rel="apple-touch-icon" href="${up}assets/apple-touch-icon.png">
<link rel="stylesheet" href="${up}styles.css">
</head>
<body>
<header class="site"><div class="wrap">
  <a class="logo" href="${up}index.html"><img class="logo-ghost" src="${up}assets/ghost-mini.svg" alt="" width="26" height="29">PerkaBoo</a>
  <nav><a href="${up}index.html">Home</a><a href="${up}cards/index.html">Card credits</a><a href="${up}support.html">Support</a><a href="${up}privacy.html">Privacy</a><a href="${up}terms.html">Terms</a></nav>
</div></header>
<main><article class="wrap">
${body}
</article></main>
<footer class="site"><div class="wrap">
  <div><a href="${up}support.html">Support</a><a href="${up}privacy.html">Privacy Policy</a><a href="${up}terms.html">Terms of Use</a></div>
  <p>&copy; 2026 SJBApps. PerkaBoo is not affiliated with, endorsed by, or sponsored by any card issuer or bank. Card names are used only to identify the cards you hold. Benefit details come from public terms and can be out of date; please confirm with your issuer. PerkaBoo is not financial advice.</p>
</div></footer>
</body>
</html>
`;
};

const disclaimer = `<p class="note">Details come from the issuer's public terms and reputable reviews, and issuers change credits often. Always confirm the current terms with your issuer before relying on a credit. PerkaBoo is not affiliated with any card issuer or bank.</p>`;
const cta = `<div class="tile"><h3>Never miss one of these</h3><p>PerkaBoo lists every credit on your cards, reminds you before each one expires, and keeps your data on your phone. No bank login, no account, no card numbers. <span class="badge soft">Coming soon to the App Store</span></p></div>`;

const cards = lib.cards.filter((c) => PUBLISH.has(c.id));
const slug = (c) => c.id;
const fullName = (c) => `${c.issuer} ${c.name}`;

function cardPage(c) {
  const dates = c.benefits.map((b) => b.lastVerified).filter(Boolean).sort();
  const verified = dates[dates.length - 1];
  const rows = c.benefits.map((b) => {
    const bits = [];
    if (b.description) bits.push(esc(b.description));
    if (b.enrollmentRequired) bits.push("Enrollment required.");
    if (b.automatic) bits.push("Applied automatically while you are a member.");
    if (NOTES[`${c.id}:${b.slug}`]) bits.push(esc(NOTES[`${c.id}:${b.slug}`]));
    const amount = b.amountCents === 0 ? "A perk (no dollar value)" : b.cadence === "multiyear" ? `${money(b.amountCents)} per four years` : `${money(b.amountCents)} ${b.cadence === "annual" ? "per year" : b.cadence === "semiannual" ? "every six months" : b.cadence === "quarterly" ? "per quarter" : "per month"}`;
    return `<tr><td><strong>${esc(b.name)}</strong>${bits.length ? `<br><span class="muted">${bits.join(" ")}</span>` : ""}</td><td>${amount}</td><td>${esc(resets(b))}</td></tr>`;
  }).join("\n");
  const total = c.benefits.reduce((s, b) => s + annualValue(b), 0);
  const body = `<p class="crumbs"><a href="index.html">Card credits</a></p>
<h1>${esc(fullName(c))} credits and when they expire</h1>
<p class="lead">Every statement credit on the ${esc(fullName(c))} (annual fee ${money(c.annualFeeCents)}), what it is worth, and when it resets. Last verified ${monthName(verified)}.</p>
<table class="credits">
<thead><tr><th>Credit</th><th>Amount</th><th>Resets</th></tr></thead>
<tbody>
${rows}
</tbody>
</table>
${total > 0 ? `<p>If you used every recurring credit above in a full year, that adds up to about <strong>${money(total)}</strong> against the ${money(c.annualFeeCents)} annual fee. Most people use only some of them, which is why tracking matters.</p>` : ""}
${disclaimer}
${cta}`;
  return layout({
    title: `${fullName(c)} credits and when they expire | PerkaBoo`,
    description: `Every ${fullName(c)} statement credit, its amount and reset schedule, last verified ${verified}.`,
    path: `cards/${slug(c)}.html`,
    depth: 1,
    body,
  });
}

function indexPage() {
  const items = cards.map((c) => `<li><a href="${slug(c)}.html">${esc(fullName(c))}</a> <span class="muted">${money(c.annualFeeCents)} fee, ${c.benefits.length} credits and perks</span></li>`).join("\n");
  return layout({
    title: "Credit card credits and when they expire | PerkaBoo",
    description: "Statement credits on popular premium cards: amounts, reset schedules and what expires when.",
    path: "cards/index.html",
    depth: 1,
    body: `<h1>Credit card credits and when they expire</h1>
<p class="lead">One page per card, built from the same list the PerkaBoo app uses. <a href="../december-31.html">See what expires on December 31</a>.</p>
<ul class="plain">
${items}
</ul>
${disclaimer}
${cta}`,
  });
}

function decemberPage() {
  const groups = [
    ["Annual credits (reset every calendar year)", (b) => b.cadence === "annual" && b.resetBasis === "calendar"],
    ["Twice-a-year credits: the second-half amount", (b) => b.cadence === "semiannual" && b.resetBasis === "calendar"],
    ["Quarterly credits: the fourth-quarter amount", (b) => b.cadence === "quarterly" && b.resetBasis === "calendar"],
    ["Monthly credits: December's amount", (b) => b.cadence === "monthly" && b.resetBasis === "calendar"],
  ];
  const sections = groups.map(([title, test]) => {
    const rows = cards.flatMap((c) => c.benefits.filter((b) => test(b) && b.amountCents > 0 && !b.automatic).map((b) => ({ c, b })));
    if (rows.length === 0) return "";
    const lis = rows.map(({ c, b }) => `<li><strong>${esc(b.name)}</strong> on the <a href="cards/${slug(c)}.html">${esc(fullName(c))}</a>: ${money(b.amountCents)}</li>`).join("\n");
    return `<h2>${esc(title)}</h2>\n<ul>\n${lis}\n</ul>`;
  }).join("\n");
  const body = `<h1>Credit card credits that expire December 31</h1>
<p class="lead">Many premium-card credits reset on the calendar year, so anything unused on December 31 is gone. Here is what to check on popular cards before the year ends.</p>
${sections}
<h2>Credits that do not expire on December 31</h2>
<p>Credits that reset on your <em>card anniversary</em> (for example some travel and hotel credits) follow your own anniversary date instead, and multi-year credits such as Global Entry or TSA PreCheck last four years. Check your issuer's account for your exact dates.</p>
${disclaimer}
${cta}`;
  return layout({
    title: "Credit card credits that expire December 31 | PerkaBoo",
    description: "A checklist of statement credits on popular premium cards that reset on the calendar year, so you can use them before December 31.",
    path: "december-31.html",
    depth: 0,
    body,
  });
}

function sitemap(paths) {
  const urls = paths.map((p) => `  <url><loc>${SITE_URL}/${p}</loc></url>`).join("\n");
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`;
}

mkdirSync(resolve(root, "cards"), { recursive: true });
const written = [];
const put = (rel, content) => {
  writeFileSync(resolve(root, rel), content);
  written.push(rel);
};
for (const c of cards) put(`cards/${slug(c)}.html`, cardPage(c));
put("cards/index.html", indexPage());
put("december-31.html", decemberPage());
put("sitemap.xml", sitemap(["index.html", "support.html", "privacy.html", "terms.html", ...written.filter((p) => p.endsWith(".html"))]));
console.log(`Built ${written.length} files from library v${lib.version} (${lib.lastUpdated}); ${cards.length} cards published.`);
